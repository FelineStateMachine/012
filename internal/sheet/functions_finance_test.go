package sheet

import "testing"

func TestFinanceFunctions(t *testing.T) {
	checkFormulas(t, fixture(t), []fnCase{
		{"=PMT(0.05/12, 360, 200000)", num(-1073.6432460242795)},
		{"=PMT(0, 10, 1000)", num(-100)},
		{"=PMT(0.05, 0, 1000)", ErrNum},
		{"=PV(0.05/12, 360, -1000)", num(186281.61704607523)},
		{"=PV(0, 10, -100)", num(1000)},
		{"=FV(0.05, 10, -100)", num(1257.789253554884)},
		{"=FV(0.05, 10, -100, 0, 1)", num(1320.6787162326282)},
		{"=FV(0, 10, -100, -500)", num(1500)},
		{"=NPER(0.01, -1000, 10000)", num(10.58864445942323)},
		{"=NPER(0, -100, 1000)", num(10)},
		{"=NPER(0.01, 100, 10000)", num(-69.6607168935748)},
		{"=NPER(-1, 100, 10000)", ErrNum},
		{"=RATE(360, -1073.6432460242795, 200000)", num(0.05 / 12)},
		{"=RATE(10, 0, 0)", ErrNum},
		{"=NPV(0.1, H1:H4)", num(-19.124376750222126)},
		{"=NPV(-1, 100)", ErrDiv0},
		{"=IRR(H1:H4)", num(0.08896339469335)},
		{"=IRR(C1:C5)", ErrNum}, // no negative flow
	})
}
